// FUN_003DF7F0
#pragma schedule on
/****************************************************************************
 _rwSListDestroy

 On entry       : SList
 On exit        : TRUE if ok
 */

RwBool
_rwSListDestroy(RwSList * sList)
{
    RWFUNCTION(RWSTRING("_rwSListDestroy"));
    RWASSERT(sList);

    if ((sList->listElements) && (sList->numElementsAlloced))
    {
        RwFree(sList->listElements);
        sList->listElements = (unsigned char *)NULL;
        sList->numElementsAlloced = 0;
    }

    RwFree(sList);

    RWRETURN(TRUE);
}
