#!/usr/bin/env python3
"""Batch-decompile every still-unmatched first-party function through IDA's
Hex-Rays decompiler, as a head-start for reconstruction lanes.

This is a SECOND, independent decompiler alongside the existing m2c output
under src/generated/. It is materially better at structure: on the DMA/loop
family it correctly reconstructs nested loops and unrolled bodies that m2c
mis-renders, and it renders retail hardware MMIO addresses as MEMORY[0x...]
directly, corroborating tools/hw_access_census.py from an independent tool.

It is NOT better at the Emotion Engine's own extensions. The FPU
multiply-accumulate chain (mula.s/madda.s/madd.s/...) and the rare
EE-specific single instructions (mfthc1, pcpyld, ...) decompile to raw
`__asm { ... }` blocks -- Hex-Rays' generic MIPS model does not know their
semantics. Everything AROUND such an island still decompiles correctly;
only the island itself needs hand translation, using the measured b210
rules already recorded in docs/matching.md (e.g. the accumulator is seeded
with the SECOND addend of a*a + b*b + c*c).

Output is REFERENCE ONLY, never compiled: IDA's pseudo-types (__int64,
_DWORD, _$F0 register pseudos) are not valid MWCC input. It is written under
docs/ida_headstart/, not src/, specifically so decomp_lint's first-party
source walk (which only descends src/) never sees it.

Requires: an activated idalib venv (see idalib/README.txt in the IDA
install), and IDA opened at least once interactively to accept the license.

Usage:
    python3 tools/ida_headstart.py --report build/wibo_full.json \\
        [--elf orig/SLUS_217.82] [--out docs/ida_headstart] [--limit N]
"""

import argparse
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))

from verify import is_third_party, is_vendor_address  # noqa: E402

DISCLAIMER = """\
/* Generated by tools/ida_headstart.py -- Hex-Rays (IDA Pro 9.4) pseudocode.
 *
 * REFERENCE ONLY. This is not valid C and is never compiled: IDA's pseudo
 * types (__int64, _DWORD, _$F0 register aliases) are not MWCC input, and a
 * raw `__asm { ... }` block below is Hex-Rays declining to model an Emotion
 * Engine instruction it does not understand (FPU multiply-accumulate chains,
 * or a rare single op like mfthc1/pcpyld). Everything else in a function
 * usually decompiles correctly -- control flow, hardware MMIO addresses
 * (rendered as MEMORY[0x...]), struct layout. Translate an asm island by
 * hand using the measured b210 rules in docs/matching.md; do not guess.
 *
 * Regenerate: python3 tools/ida_headstart.py --report <verify.json>
 */

"""


def addr_of(row):
    a = row.get("addr")
    return int(str(a), 16) if isinstance(a, str) else a


def targets(report_path):
    rows = json.load(open(report_path))["results"]
    out = []
    for r in rows:
        if r["status"] != "ASM":
            continue
        if is_third_party(r["file"]) or is_vendor_address(r.get("addr")):
            continue
        out.append({"name": r["name"], "file": r["file"].replace("\\", "/"),
                    "addr": addr_of(r), "window": r.get("window") or 0})
    out.sort(key=lambda x: (x["file"], x["addr"]))
    return out


def ensure_func(addr, window):
    """Make sure IDA has a function defined at addr; return True if usable."""
    import ida_funcs
    if ida_funcs.get_func(addr) is not None:
        return True
    return ida_funcs.add_func(addr, addr + window) if window else False


def decompile_one(addr, window):
    import ida_hexrays
    if not ensure_func(addr, window):
        return None, "no function boundary at this address"
    try:
        cf = ida_hexrays.decompile(addr)
    except ida_hexrays.DecompilationFailure as exc:
        return None, str(exc)
    if cf is None:
        return None, "decompile() returned None"
    return str(cf), None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default="build/wibo_full.json")
    ap.add_argument("--elf", default="orig/SLUS_217.82")
    ap.add_argument("--out", default="docs/ida_headstart")
    ap.add_argument("--limit", type=int, default=0, help="0 = no limit")
    args = ap.parse_args()

    todo = targets(os.path.join(REPO, args.report))
    if args.limit:
        todo = todo[:args.limit]
    print("targets: %d" % len(todo))

    import idapro
    rc = idapro.open_database(os.path.join(REPO, args.elf), True)
    if rc != 0:
        sys.exit("idapro.open_database failed: rc=%d" % rc)
    import ida_auto
    ida_auto.auto_wait()

    by_file = {}
    ok = fail = 0
    failures = []
    for t in todo:
        text, err = decompile_one(t["addr"], t["window"])
        if text is None:
            fail += 1
            failures.append((t["name"], t["addr"], err))
            continue
        ok += 1
        header = ("// %s  addr 0x%08x  window %dB\n"
                  % (t["name"], t["addr"], t["window"]))
        by_file.setdefault(t["file"], []).append(header + text)

    idapro.close_database(False)

    for rel_file, blocks in by_file.items():
        out_path = os.path.join(REPO, args.out, rel_file)
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        with open(out_path, "w") as f:
            f.write(DISCLAIMER)
            f.write("\n\n".join(blocks))
            f.write("\n")

    print("decompiled: %d ok, %d failed, across %d files -> %s"
          % (ok, fail, len(by_file), args.out))
    if failures:
        print("failures (first 20):")
        for name, addr, err in failures[:20]:
            print("  %-16s 0x%08x  %s" % (name, addr, err))
    return 0


if __name__ == "__main__":
    sys.exit(main())
