def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("addresses", nargs="*", metavar="ADDR",
                        help="canonical function addresses (hex, 8 digits)")
    parser.add_argument("--all-nonmatching", action="store_true",
                        help="extract every NONMATCHING function from a verify.py --json report")
    parser.add_argument("--report", metavar="PATH", default=str(DEFAULT_REPORT),
                        help="verify.py --json report (default: %(default)s)")
    parser.add_argument("--group", metavar="NAME",
                        help="override the output group directory for bare addresses")
    parser.add_argument("--out-dir", metavar="PATH", default="asm/nonmatchings",
                        help="output root (default: %(default)s)")
    parser.add_argument("--check", action="store_true",
                        help="report what would change without writing anything")
    args = parser.parse_args()

    cfg = V.load_config()
    target = V._read_json(V.TARGET)
    windows_map = V._read_json(V.FUNCTION_WINDOWS)
    if windows_map.get("program") != "SLUS_217.82" or windows_map.get("sha1") != target["elf"]["sha1"]:
        V._die("slus21782_functions.json does not describe the configured P4 USA target")
    windows = windows_map["windows"]
    retail = V.RetailElf(cfg["retail_elf"], target, windows_map["sha1"])

    jobs: list[dict] = []
    if args.addresses:
        for text in args.addresses:
            try:
                addr = int(text, 16)
            except ValueError:
                parser.error(f"not a hex address: {text}")
            if f"{addr:08x}" not in windows:
                parser.error(f"{text} is not a canonical function window")
            if args.group:
                group = args.group
            else:
                owner = find_owner_file(addr)
                if owner is None:
                    parser.error(f"no src file owns a FUN_{addr:08x} marker; pass --group")
                group = owner.stem
            jobs.append(dict(addr=addr, window=windows[f"{addr:08x}"], group=group))
    if args.all_nonmatching:
        report = Path(args.report)
        if not report.is_file():
            parser.error(f"report not found: {report}")
        jobs.extend(report_jobs(report))
    if not jobs:
        parser.error("nothing to do: pass addresses and/or --all-nonmatching")
    # A corrupt report (window disagreeing with the canonical map) must not
    # silently produce a wrong-window .s; refuse it up front.
    for job in jobs:
        canonical = windows.get(f"{job['addr']:08x}")
        if canonical is not None and canonical != job["window"]:
            parser.error(
                f"window for func_{job['addr']:08x} is {job['window']}B but the "
                f"canonical map says {canonical}B; fix the report")
    # A bare-address --group override must not leak into report-driven jobs.
    for job in jobs:
        if not job.get("group"):
            job["group"] = args.group or "unknown"

    asm_dir = REPO / "asm"
    macro_lines = (asm_dir / "macro.inc").read_bytes().decode("ascii").splitlines(keepends=True)
    try:
        asm_tool = find_gnu_tool("mipsel-linux-gnu-as", "P4_AS")
    except SystemExit as error:
        parser.error(str(error))

    out_root = Path(args.out_dir)
    if not out_root.is_absolute():
        out_root = REPO / out_root
    needed = {job["addr"] for job in jobs}
    splat_index = build_splat_index(asm_dir, needed)

    counts = {"sliced": 0, "synthesised": 0, "unchanged": 0, "written": 0,
              "failed": 0}
    changed: list[str] = []
    failures: list[dict] = []
    with tempfile.TemporaryDirectory(prefix="p4-asm-") as tmpdir:
        for job in sorted(jobs, key=lambda j: j["addr"]):
            addr, window, group = job["addr"], job["window"], job["group"]
            out_path = out_root / group / f"func_{addr:08x}.s"
            try:
                kind, lines = extract_function(
                    addr, window, retail, windows, splat_index, asm_tool,
                    macro_lines, asm_dir, Path(tmpdir))
            except ExtractionFailure as error:
                failures.append(dict(addr=f"{addr:08x}", group=group, reason=str(error)))
                counts["failed"] += 1
                print(f"FAILED  func_{addr:08x} ({group}): {error}")
                continue
            counts[kind] += 1
            content = "".join(lines)
            previous = out_path.read_text(encoding="utf-8") if out_path.is_file() else None
            if previous == content:
                counts["unchanged"] += 1
                state = "ok (unchanged)"
            elif args.check:
                changed.append(_display_path(out_path))
                state = "would write"
            else:
                out_path.parent.mkdir(parents=True, exist_ok=True)
                out_path.write_bytes(content.encode("utf-8"))
                counts["written"] += 1
                changed.append(_display_path(out_path))
                state = "written"
            print(f"{state:<16} {kind:<12} {include_asm_line(group, addr)}")

    print(f"\nextracted: {counts['sliced'] + counts['synthesised']} function(s)")
    print(f"  sliced from splat:     {counts['sliced']}")
    print(f"  synthesised from ELF:  {counts['synthesised']}")
    print(f"  written:               {counts['written']}")
    print(f"  unchanged:             {counts['unchanged']}")
    print(f"  failed:                {counts['failed']}")
    if failures:
        for failure in failures:
            print(f"  FAILED func_{failure['addr']} ({failure['group']}): {failure['reason']}")
    if changed:
        print(f"\n{'would change' if args.check else 'changed'} {len(changed)} file(s):")
        for rel in changed:
            print(f"  {rel}")
    if not args.check:
        print("\nINCLUDE_ASM lines (verbatim, one per generated file):")
        failed_addrs = {failure["addr"] for failure in failures}
        for job in sorted(jobs, key=lambda j: j["addr"]):
            if f"{job['addr']:08x}" in failed_addrs:
                continue
            print(include_asm_line(job["group"], job["addr"]))
    raise SystemExit(1 if failures or (args.check and changed) else 0)


if __name__ == "__main__":
    main()
