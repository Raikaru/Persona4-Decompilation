#!/usr/bin/env python3
"""Generate INCLUDE_ASM fallback ``.s`` files for canonical functions.

For every canonical function address this tool writes
``asm/nonmatchings/<group>/func_<addr>.s`` -- the assembly file an
``INCLUDE_ASM("asm/nonmatchings/<group>", func_<addr>)`` marker in a real
translation unit needs.  ``<group>`` defaults to the stem of the C file that
owns the function's ``// FUN_<addr>`` marker (so one TU's fallbacks sit
together), and can be overridden with ``--group``.

The bytes are sourced from the retail ELF.  We prefer *slicing* the function
out of the splat output (``asm/code1.s`` / ``asm/code2.s`` / ``asm/main.s``,
in that order) because splat already emitted ``glabel`` labels and real
symbol references (``jal func_XXXXXXXX``, ``%hi/%lo`` pairs), which is what
keeps the assembled object relocatable.  A function splat did not label -- or
whose label layout disagrees with the canonical window -- is *synthesised*
as ``.word 0x........`` literals decoded from the retail ELF.

Every candidate file is verified before it is written, with three checks
that are all mandatory for the mwccgap INCLUDE_ASM pipeline to work:

  * placeholder length: the mwccgap preprocessor replaces each counted
    instruction line with one 4-byte ``nop`` placeholder, so the number of
    instruction lines in the ``.s`` times four must be exactly the canonical
    window size;
  * assembly: the file assembles cleanly with the same GNU binutils the
    build uses (``mipsel-linux-gnu-as``, via WSL when required);
  * bytes: the assembled ``.text`` is exactly window bytes long and matches
    the retail window bytes once relocation targets are masked
    (``verify.compare``).

A candidate that fails any check is discarded and the next fallback is
tried (slice -> synthesis); a function that fails both is reported and
never written -- a broken fallback would break the whole TU that includes
it.  Existing files are never deleted.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TOOLS = REPO / "tools"
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))

import verify as V  # noqa: E402  (repo helpers: RetailElf, mask_bytes, compare)
from asm import (  # noqa: E402  (repo helpers: GNU binutils plumbing)
    BYTES_RE,
    ERR_RE,
    byte_line,
    ensure_local_labels,
    find_gnu_tool,
)

SPLAT_FILES = ("code1.s", "code2.s", "main.s")
GLABEL_RE = re.compile(r"^glabel\s+(\S+)")
# Byte comments in splat output: "/* <file-offset> <vram> <bytes> */" (both
# the code1.s and code2.s comment styles carry vram as the second field).
VRAM_RE = re.compile(r"/\*\s*[0-9A-Fa-f]+\s+([0-9A-Fa-f]{8})\s+[0-9A-Fa-f]{8}")
# Word-level relocation mask, as tools/asm.py uses it for its retail diff.
ASM_RELOC_MASK_SIZE = {2: 4, 4: 4, 5: 4, 6: 4, 7: 4}
DEFAULT_REPORT = Path("C:/tmp/p4_verify_report.json")
MAX_PASSES = 128

HEADER_LINES = [".section .text\n", ".set noat\n", ".set noreorder\n"]


# --------------------------------------------------------------------------
# mwccgap placeholder accounting
# --------------------------------------------------------------------------

def count_placeholder_words(lines: list[str]) -> int:
    """Replicate the mwccgap ``preprocess_s_file`` line counting (.text mode).

    Every line the preprocessor does NOT skip becomes one 4-byte ``nop``
    placeholder in the compiled object, so a ``.s`` whose counted-line count
    is N produces a function symbol of exactly 4*N bytes.  The generated
    files only contain directives/labels from the skip list plus one
    instruction (or ``.word``) per counted line.
    """
    count = 0
    for line in lines:
        s = line.strip()
        if not s:
            continue
        if s.startswith((".section", ".set", ".include", ".size",
                         ".align", ".balign")):
            continue
        if s.startswith(("glabel", "jlabel", "alabel", "endlabel",
                         "enddlabel", "nonmatching")):
            continue
        if s.startswith(".L") and s.endswith(":"):
            continue
        if s.startswith("/* Generated by spimdisasm"):
            continue
        if s.startswith("/* Handwritten function"):
            continue
        if s.startswith("/*") and not re.sub(r"/\*.*?\*/", "", s).strip():
            continue
        if s.startswith("#"):
            continue
        count += 1
    return count


# --------------------------------------------------------------------------
# splat indexing and slicing
# --------------------------------------------------------------------------

def build_splat_index(asm_dir: Path, needed: set[int] | None = None,
                      names: tuple[str, ...] = SPLAT_FILES
                      ) -> dict[int, tuple[Path, int]]:
    """Map function start address -> (splat file, glabel line number).

    The address is taken from the first instruction line after each
    ``glabel`` (its byte comment carries the vram), which handles splat
    labels that are not named ``func_XXXXXXXX``.  ``needed`` lets the scan
    stop early once every requested address has been found; ``needed=None``
    indexes the whole file.  ``names`` is injectable for tests.
    """
    index: dict[int, tuple[Path, int]] = {}
    for name in names:
        path = asm_dir / name if not Path(name).is_absolute() else Path(name)
        if not path.is_file():
            continue
        pending: tuple[int, str] | None = None
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            for lineno, line in enumerate(handle):
                match = GLABEL_RE.match(line)
                if match:
                    pending = (lineno, match.group(1))
                    continue
                if pending is None:
                    continue
                match = VRAM_RE.search(line)
                if match:
                    index.setdefault(int(match.group(1), 16), (path, pending[0]))
                    pending = None
                    if needed is not None and needed <= set(index):
                        return index
    return index


def slice_function(path: Path, glabel_lineno: int, next_glabel: int) -> list[str]:
    """Return the splat lines from ``glabel`` up to (not including) the next glabel."""
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for _ in range(glabel_lineno):
            next(handle)
        return [line for line, _ in zip(handle, range(next_glabel - glabel_lineno))]


def slice_matches_window(raw_lines: list[str], window: int) -> bool:
    """True iff the splat slice's counted instruction lines fill the window.

    A slice that is short of the window means splat's label layout disagrees
    with the canonical window (splat split the function, or the canonical
    boundary is later) -- such a slice is REJECTED rather than padded: a
    padded hybrid would assemble to the right size while its instruction
    stream could still disagree with retail.  The caller falls back to full
    synthesis from the ELF, which is byte-exact for the whole window by
    construction.  (A slice longer than the window is rejected the same
    way.)
    """
    return count_placeholder_words(HEADER_LINES + clean_slice(raw_lines)) * 4 == window


def clean_slice(lines: list[str]) -> list[str]:
    """Strip splat boundary noise that the preprocessor would skip anyway.

    Only lines the mwccgap preprocessor ignores are removed (blank lines,
    ``endlabel``/``nonmatching``/``matching`` markers, whole-line comments),
    so the placeholder count of the emitted file is identical to the raw
    slice.  Instruction lines and ``.L`` labels are never touched.
    """
    cleaned: list[str] = []
    for line in lines:
        s = line.strip()
        if not s:
            continue
        if s.startswith(("endlabel", "enddlabel", "nonmatching", "matching")):
            continue
        if s.startswith("/*") and not re.sub(r"/\*.*?\*/", "", s).strip():
            continue
        cleaned.append(line)
    return cleaned


def next_glabel_lineno(path: Path, glabel_lineno: int) -> int | None:
    """Line number of the next ``glabel`` line after ``glabel_lineno`` (or None at EOF)."""
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for _ in range(glabel_lineno + 1):
            next(handle)
        for lineno, line in enumerate(handle, start=glabel_lineno + 1):
            if GLABEL_RE.match(line):
                return lineno
    return None


# --------------------------------------------------------------------------
# synthesis from the retail ELF
# --------------------------------------------------------------------------

def synthesise(addr: int, window: int, retail_bytes: bytes,
               windows: dict) -> list[str]:
    """Build a pure ``.word`` fallback decoded from the retail window.

    JAL instructions whose target is another canonical function get the same
    ``.reloc .-4, R_MIPS_26, func_XXXXXXXX`` annotation the existing
    ``asm/nonmatchings/btlVoiceCreatePacket.s`` uses, so the object stays
    relocatable; every other word is emitted verbatim (byte-exact against
    retail by construction).
    """
    lines: list[str] = []
    lines.append(f"glabel func_{addr:08x}\n")
    for offset in range(0, window, 4):
        if offset + 4 > len(retail_bytes):
            break  # a truncated window can never verify; fail cleanly instead
        word = struct.unpack_from("<I", retail_bytes, offset)[0]
        if word & 0xFC000000 == 0x0C000000:  # jal
            target = (word & 0x03FFFFFF) << 2
            if f"{target:08x}" in windows:
                lines.append(
                    f".word 0x{word & 0xFC000000:08X}; .reloc .-4, R_MIPS_26, "
                    f"func_{target:08X}\n"
                )
                continue
        lines.append(f".word 0x{word:08X}\n")
    return lines


# --------------------------------------------------------------------------
# GNU binutils plumbing (same tools and flags as tools/asm.py)
# --------------------------------------------------------------------------

def _wslpath(path: str) -> str:
    proc = subprocess.run(
        ["wsl", "-d", os.environ.get("P4_WSL_DISTRO", "Debian"), "--",
         "wslpath", "-a", str(path).replace("\\", "/")],
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
    )
    if proc.returncode:
        raise RuntimeError(proc.stdout.strip())
    return proc.stdout.strip()


def _tool_arg(tool, arg: str | Path) -> str:
    s = str(arg)
    if tool.wsl and (len(s) >= 3 and s[1] == ":" and s[2] in ("/", "\\") or "\\" in s):
        return _wslpath(s)
    return s


def _run(tool, args: list[str | Path], stdin: bytes = b"") -> subprocess.CompletedProcess:
    cmd = list(tool.argv) + [_tool_arg(tool, arg) for arg in args]
    return subprocess.run(cmd, input=stdin, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT)


def _error_lines(log: str) -> list[int]:
    return sorted({int(m.group(1) or m.group(2)) for m in ERR_RE.finditer(log)})


def _assemble_once(asm_tool, lines: list[str], out: Path, macro_lines: list[str],
                   include_dir: Path) -> str:
    """Assemble macro.inc + lines with GNU as; return "" on success, else the log.

    The macro.inc prefix mirrors mwccgap's Assembler (which prepends the
    macros the ``glabel`` in every emitted file expands to); the flag set
    matches tools/asm.py.  ``-no-pad-sections`` keeps ``.text`` exactly the
    emitted bytes so the window-size check is exact.
    """
    with tempfile.NamedTemporaryFile("w", suffix=".s", delete=False,
                                     encoding="utf-8", newline="\n") as handle:
        for macro_line in macro_lines:
            handle.write(macro_line)
        for line in lines:
            handle.write(line)
        tmp = Path(handle.name)
    try:
        proc = _run(asm_tool, [
            "-EL", "-I", include_dir, "-G", "128",
            "-march=r5900", "-mabi=eabi", "-no-pad-sections", "-o", out, tmp,
        ])
        log = proc.stdout.decode("utf-8", "replace")
        if proc.returncode:
            return log
        return ""
    finally:
        tmp.unlink(missing_ok=True)


def _relocated_words(obj: bytes, sections: list[dict], text_index: int,
                     endian: str) -> set[int]:
    """Offsets (word-aligned) of words carrying a relocation in .text."""
    relocated: set[int] = set()
    for section in sections:
        if section["type"] != 9 or section["info"] != text_index:
            continue
        entries = section["entsize"] or 8
        for offset in range(section["offset"], section["offset"] + section["size"], entries):
            r_offset, info = struct.unpack_from(endian + "II", obj, offset)
            mask = ASM_RELOC_MASK_SIZE.get(info & 0xFF)
            if mask is None:
                continue
            for step in range(0, mask, 4):
                relocated.add(((r_offset + step) // 4) * 4)
    return relocated


def assemble_with_repair(lines: list[str], asm_tool, macro_lines: list[str],
                         asm_dir: Path, retail_blob: bytes, ref_lo: int,
                         addr: int, out: Path) -> tuple[bool, str, bytes, list[dict]]:
    """Assemble with asm.py's two repair passes; return (ok, log, .text, relocs).

    Pass 1 rewrites lines GNU as rejects (misdecoded words such as ddiv)
    to ``.word`` from their byte comments.  Pass 2 compares non-relocated
    words against retail and rewrites valid-looking wrong words the same
    way.  This mirrors tools/asm.py::assemble; the returned .text is the
    first-window slice the mwccgap transplant would use.
    """
    lines = ensure_local_labels(lines)
    log = ""
    for _ in range(MAX_PASSES):
        log = _assemble_once(asm_tool, lines, out, macro_lines, asm_dir)
        if log:
            bad = _error_lines(log)
            changed = False
            for line_no in bad:
                index = line_no - 1 - len(macro_lines)
                if 0 <= index < len(lines):
                    replacement = byte_line(lines[index])
                    if replacement and replacement != lines[index]:
                        lines[index] = replacement
                        changed = True
            if not changed:
                return False, log, b"", []
        else:
            break
    else:
        return False, "too many assembler repair passes", b"", []

    obj = out.read_bytes()
    endian, sections = V.elf_sections(obj)
    text = next((s for s in sections if s["name"] == ".text"), None)
    if text is None:
        return False, "assembled object has no .text", b"", []
    body = obj[text["offset"]:text["offset"] + text["size"]]

    relocated = _relocated_words(obj, sections, text["idx"], endian)
    addr_line: dict[int, int] = {}
    for index, line in enumerate(lines):
        match = BYTES_RE.search(line)
        if match and ": data" not in line:
            addr_line[int(match.group(1), 16)] = index
    for _ in range(MAX_PASSES):
        orig = retail_blob[ref_lo:ref_lo + len(body)]
        diff_words = sorted({
            (index // 4) * 4
            for index in range(min(len(body), len(orig)))
            if body[index] != orig[index] and ((index // 4) * 4) not in relocated
        })
        if not diff_words:
            break
        changed = False
        for word_offset in diff_words:
            index = addr_line.get(addr + word_offset)
            if index is None:
                continue
            replacement = byte_line(lines[index])
            if replacement and replacement != lines[index]:
                lines[index] = replacement
                changed = True
        if not changed:
            return False, f"unresolved non-reloc diffs at {[hex(addr + w) for w in diff_words[:8]]}", b"", []
        log = _assemble_once(asm_tool, lines, out, macro_lines, asm_dir)
        if log:
            return False, log, b"", []
        obj = out.read_bytes()
        endian, sections = V.elf_sections(obj)
        text = next(s for s in sections if s["name"] == ".text")
        body = obj[text["offset"]:text["offset"] + text["size"]]

    relocs: list[dict] = []
    for section in sections:
        if section["type"] != 9 or section["info"] != text["idx"]:
            continue
        entries = section["entsize"] or 8
        for offset in range(section["offset"], section["offset"] + section["size"], entries):
            r_offset, info = struct.unpack_from(endian + "II", obj, offset)
            relocs.append(dict(offset=r_offset, r_type=info & 0xFF))
    return True, "", body, relocs


# --------------------------------------------------------------------------
# per-function extraction
# --------------------------------------------------------------------------

def _passed(checks: dict) -> bool:
    """True when every mandatory verification check passed."""
    return (checks.get("placeholder") is True
            and checks.get("assembles") is True
            and checks.get("size") is True
            and checks.get("masked_diff") == 0)


class ExtractionFailure(Exception):
    pass


def extract_function(addr: int, window: int, retail: V.RetailElf, windows: dict,
                     splat_index: dict[int, tuple[Path, int]], asm_tool,
                     macro_lines: list[str], asm_dir: Path, tmpdir: Path,
                     ) -> tuple[str, list[str]]:
    """Return (kind, lines) for addr, preferring a splat slice over synthesis.

    A slice is accepted only when it verifies end to end (placeholder size,
    clean assembly, exact .text size, masked byte equality).  A slice whose
    span disagrees with the canonical window -- short OR long -- is rejected
    in favour of full synthesis, so the emitted file always covers the
    entire window and is byte-exact by construction.
    """
    retail_bytes = retail.bytes_at(addr, window)
    load_vaddr, load_offset, load_filesz = retail.segs[0]
    retail_blob = retail.data[load_offset:load_offset + load_filesz]
    ref_lo = addr - load_vaddr

    entry = splat_index.get(addr)
    slice_checks: dict = {}
    if entry is not None:
        path, glabel_lineno = entry
        end = next_glabel_lineno(path, glabel_lineno)
        if end is not None:
            raw = slice_function(path, glabel_lineno, end)
            if slice_matches_window(raw, window):
                sliced_lines = HEADER_LINES + clean_slice(raw)
                sliced_lines.append(f".size func_{addr:08x}, 0x{window:x}\n")
                slice_checks, repaired = verify_lines(
                    sliced_lines, asm_tool, macro_lines, asm_dir,
                    retail, retail_blob, ref_lo, addr, window, tmpdir)
                if _passed(slice_checks):
                    return "sliced", repaired
            else:
                slice_checks["placeholder"] = False
                slice_checks["placeholder_detail"] = (
                    f"slice span != canonical window")


    synth_lines = HEADER_LINES + synthesise(addr, window, retail_bytes, windows)
    synth_lines.append(f".size func_{addr:08x}, 0x{window:x}\n")
    synth_checks, repaired = verify_lines(
        synth_lines, asm_tool, macro_lines, asm_dir,
        retail, retail_blob, ref_lo, addr, window, tmpdir)
    if _passed(synth_checks):
        return "synthesised", repaired
    raise ExtractionFailure(
        f"slice {_checks_short(slice_checks)}; synthesis {_checks_short(synth_checks)}"
    )


def _checks_short(checks: dict) -> str:
    """Compact description of failed verification checks."""
    if not checks:
        return "not attempted"
    problems = []
    for key in ("placeholder", "assembles", "size", "masked_diff"):
        if key in checks and not checks[key]:
            detail = checks.get(key + "_detail") or checks.get("assemble_log") or ""
            problems.append(f"{key} failed {detail}".strip())
    return "; ".join(problems) if problems else "verification failed"


def verify_lines(lines: list[str], asm_tool, macro_lines: list[str], asm_dir: Path,
                 retail: V.RetailElf, retail_blob: bytes, ref_lo: int, addr: int,
                 window: int, tmpdir: Path) -> tuple[dict, list[str]]:
    """Run all three mandatory checks; return (checks dict, repaired lines)."""
    checks: dict = {}
    placeholder = count_placeholder_words(lines) * 4
    checks["placeholder"] = placeholder == window
    if not checks["placeholder"]:
        checks["placeholder_detail"] = f"{placeholder}B placeholder vs {window}B window"
        return checks, lines
    out = tmpdir / f"func_{addr:08x}.o"
    ok, log, body, relocs = assemble_with_repair(
        lines, asm_tool, macro_lines, asm_dir, retail_blob, ref_lo, addr, out)
    checks["assembles"] = ok
    if not ok:
        checks["assemble_log"] = log.strip()[:400]
        return checks, lines
    # The repair passes rewrite lines one-for-one and only insert skipped
    # .L labels, so the placeholder count is invariant -- verify anyway.
    if count_placeholder_words(lines) * 4 != window:
        checks["placeholder"] = False
        checks["placeholder_detail"] = "placeholder count changed during repair"
        return checks, lines
    checks["size"] = len(body) == window
    if not checks["size"]:
        checks["size_detail"] = f"{len(body)}B assembled vs {window}B window"
        return checks, lines
    difference, first = V.compare(body, relocs, retail.bytes_at(addr, window))
    checks["masked_diff"] = difference
    if difference:
        checks["first_diffs"] = first[:16]
    return checks, lines


