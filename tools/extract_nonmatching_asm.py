def find_owner_file(addr: int, src_root: Path | None = None) -> Path | None:
    """Locate the src file whose ``// FUN_<addr>`` marker owns this function."""
    if src_root is None:
        src_root = REPO / "src"
    pattern = re.compile(r"^\s*//\s*FUN_%08x\b" % addr, re.IGNORECASE)
    for path in sorted(src_root.rglob("*.c")):
        if V.is_generated(path):
            continue
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            if any(pattern.match(line) for line in handle):
                return path
    return None


def report_jobs(report_path: Path) -> list[dict]:
    """Read NONMATCHING entries out of a ``verify.py --json`` report."""
    report = json.loads(report_path.read_text(encoding="utf-8"))
    jobs = []
    for entry in report.get("results", []):
        if entry.get("status") != "NONMATCHING":
            continue
        jobs.append(dict(
            addr=int(entry["addr"], 16),
            window=int(entry["window"]),
            group=Path(str(entry["file"]).replace("\\", "/")).stem,
        ))
    return jobs


def _display_path(path: Path) -> str:
    """Repo-relative path when under the repo, absolute path otherwise."""
    try:
        return str(path.relative_to(REPO))
    except ValueError:
        return str(path)


def include_asm_line(group: str, addr: int) -> str:
    """The exact INCLUDE_ASM line the conversion tool should emit verbatim.

    The second argument must be UNQUOTED: this repo's mwccgap regex
    (``INCLUDE_ASM\\\"(.*)\", (.*)\\\"``) and verify.py's INCLUDE_MARKER_RE
    both take the function name as a bare identifier, and the line must sit
    directly under the ``// FUN_<addr>`` marker for scan_markers to flag it
    as an ASM fallback.
    """
    return f'INCLUDE_ASM("asm/nonmatchings/{group}", func_{addr:08x})'


