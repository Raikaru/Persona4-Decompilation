#!/usr/bin/env python3
"""Batch-decompile every still-unmatched first-party function through Ghidra.

This is a THIRD reconstruction reference, alongside the Hex-Rays corpus in
docs/ida_headstart (tools/ida_headstart.py) and the raw retail disassembly
(build/RECON_dis.py). It exists because the two decompilers fail in
different places, and Ghidra -- via the `ghidra-emotionengine-reloaded`
extension already backing build/RECON_dis.py -- is materially better at the
Emotion Engine's 128-bit world:

  * It has a real 128-bit type. Quadword values come out as
    `undefined1 auVar3 [16]` instead of being split or dropped.
  * It models VU0 macro-mode ops as intrinsics, e.g. `auVar3 = _sqc2(in_vf0)`,
    where Hex-Rays emits an opaque `__asm { }` island that severs dataflow
    for the rest of the function.
  * MMI and COP2 generally survive as expressions rather than islands.

Measured on the same function (0x004aaee0, effBlurFilter.c): Hex-Rays
produces an __asm island; Ghidra produces a complete function body with the
sqc2 lifted. After the plugin work in tools/ida_plugin/, 362 of the 1562
functions in the Hex-Rays corpus still contain an island; those are exactly
the ones this corpus is for.

Conversely Hex-Rays is usually the nicer read for ordinary integer code, so
neither corpus supersedes the other -- lanes should consult whichever one is
clean for their target, and cross-check when both are.

Output mirrors the src/ layout under docs/ghidra_headstart/, same convention
as docs/ida_headstart/.

Usage:
    python3 tools/ghidra_headstart.py --report build/postClean3.json
    python3 tools/ghidra_headstart.py --report build/postClean3.json --islanded-only
    python3 tools/ghidra_headstart.py --report build/postClean3.json --limit 20

Requires the headless Ghidra server to be running (see build/RECON_dis.py):
    gmcp serve --port 8091 --file orig/SLUS_217.82

Only stdlib, so it runs fine under `python -E -s` with PYTHONNOUSERSITE=1.
"""

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTDIR = os.path.join(REPO, "docs", "ghidra_headstart")
IDADIR = os.path.join(REPO, "docs", "ida_headstart")
PORT = 8091

# Address ranges belonging to vendor/third-party code (ee-gcc built), which
# is not part of the first-party matching effort.
VENDOR_RANGES = ((0x00417510, 0x0044E830), (0x004BD628, 0x0052D8C0))

DISCLAIMER = """\
/*
 * Generated by tools/ghidra_headstart.py -- Ghidra decompiler output.
 *
 * REFERENCE ONLY. This is not valid C and is never compiled.
 *
 * Ghidra pseudo-types (`undefined1 [16]`, `undefined4`, `code *`, `uint`,
 * `ulong`) and its `FUN_xxxxxxxx` / `DAT_xxxxxxxx` naming are decompiler
 * artifacts -- translate them into the project's own conventions
 * (s8/u8/s16/u16/s32/u32/s64/u64/f32 and the real func_xxxxxxxx names)
 * before writing any source.
 *
 * Why this corpus exists: Ghidra's Emotion Engine support models the PS2's
 * 128-bit register file and VU0 macro-mode ops (you will see
 * `undefined1 auVar [16]` and intrinsics like `_sqc2(...)`), where Hex-Rays
 * emits an opaque `__asm { }` island that hides the surrounding dataflow.
 * For ordinary integer code the Hex-Rays corpus in docs/ida_headstart is
 * usually the easier read. Use whichever is clean for your target; when both
 * are, cross-check them against each other and against the retail
 * disassembly from build/RECON_dis.py.
 *
 * Regenerate: python3 tools/ghidra_headstart.py --report <verify json>
 */
"""


def is_vendor(addr):
    return any(lo <= addr < hi for lo, hi in VENDOR_RANGES)


def http_get(path, params, timeout=180):
    url = "http://127.0.0.1:%d%s?%s" % (PORT, path, urllib.parse.urlencode(params))
    with urllib.request.urlopen(url, timeout=timeout) as r:
        return r.read().decode("utf-8", "replace")


def http_post(path, payload, timeout=180):
    url = "http://127.0.0.1:%d%s" % (PORT, path)
    data = json.dumps(payload).encode()
    req = urllib.request.Request(
        url, data=data, headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read().decode("utf-8", "replace")


def islanded_functions():
    """Names whose Hex-Rays pseudocode still contains an __asm island."""
    out = set()
    for root, _, files in os.walk(IDADIR):
        for fn in files:
            if not fn.endswith(".c"):
                continue
            txt = open(os.path.join(root, fn), errors="replace").read()
            parts = re.split(r"^// (func_[0-9a-f]{8})\s+addr ", txt, flags=re.M)
            for i in range(1, len(parts), 2):
                if "__asm" in parts[i + 1]:
                    out.add(parts[i])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", required=True, help="verify.py --json output")
    ap.add_argument("--limit", type=int, default=0, help="0 = no limit")
    ap.add_argument(
        "--islanded-only",
        action="store_true",
        help="only functions whose Hex-Rays output still has an __asm island",
    )
    args = ap.parse_args()

    rows = json.load(open(args.report))["results"]
    islanded = islanded_functions() if args.islanded_only else None
    if islanded is not None:
        print("functions islanded in the Hex-Rays corpus: %d" % len(islanded))

    targets = []
    for r in rows:
        if r.get("status") != "ASM":
            continue
        addr = int(r["addr"], 16)
        if is_vendor(addr):
            continue
        if islanded is not None and r["name"] not in islanded:
            continue
        targets.append((r["file"], r["name"], addr, r.get("window") or 0))
    targets.sort(key=lambda t: (t[0], t[2]))
    if args.limit:
        targets = targets[: args.limit]
    print("targets: %d" % len(targets))

    by_file = {}
    ok = failed = 0
    failures = []
    for path, name, addr, window in targets:
        a = "0x%08x" % addr
        try:
            # The server's program has no function boundaries by default;
            # create_function is idempotent enough to call unconditionally
            # (an existing function just reports success for the same entry).
            try:
                http_post(
                    "/create_function",
                    {"address": a, "disassemble_first": True},
                    timeout=120,
                )
            except Exception:
                pass  # may already exist; the decompile below is the real test
            body = http_get("/decompile_function", {"address": a}, timeout=300)
        except Exception as e:  # noqa: BLE001 - report and continue
            failed += 1
            failures.append((name, a, str(e)[:70]))
            continue

        body = body.strip()
        if not body or body.startswith("{\"error\""):
            failed += 1
            failures.append((name, a, body[:70] or "empty"))
            continue

        header = "// %s  addr %s  window %dB\n" % (name, a, window)
        by_file.setdefault(path, []).append(header + body + "\n")
        ok += 1

    for path, blocks in by_file.items():
        out_path = os.path.join(OUTDIR, path)
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        with open(out_path, "w") as f:
            f.write(DISCLAIMER)
            f.write("\n\n")
            f.write("\n\n".join(blocks))
            f.write("\n")

    print(
        "decompiled: %d ok, %d failed, across %d files -> docs/ghidra_headstart"
        % (ok, failed, len(by_file))
    )
    if failures:
        print("failures (first 20):")
        for name, a, err in failures[:20]:
            print("  %-16s %s  %s" % (name, a, err))
    return 0


if __name__ == "__main__":
    sys.exit(main())
