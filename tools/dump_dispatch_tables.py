#!/usr/bin/env python3
"""Decode the retail dispatch tables from image.bin and write docs/dispatch_tables.md.

A VA maps to image.bin at file offset VA - 0x100000. Handler names come from the
`// FUN_XXXXXXXX` markers under src/ (the definition below each marker). Command
names for script groups 0-3 come from the p4flow library (outside git), keyed by
the full command id group << 12 | index.

Usage: python tools/dump_dispatch_tables.py [--image image.bin] [--p4flow DIR] [--out docs/dispatch_tables.md]
"""

import argparse
import json
import pathlib
import re
import struct
import sys

IMAGE_BASE = 0x100000
REPO = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_P4FLOW = REPO.parent / "p4flow"

# Script command groups: base VA of the 8-byte {cmds, count} record, expected count, p4flow file.
SCRIPT_GROUPS = {
    0: (0x63D070, 121, "Common.json"),
    1: (0x63D440, 51, "Field.json"),
    2: (0x63D5E0, 276, "AI.json"),
    3: (0x63DE80, 61, "Event.json"),
}
GROUP_TABLE_VA = 0x748530  # ScrCmdGroup D_00748530[]

CODEFUNC_TABLE_VA = 0x63E2B0  # CodeFunc D_0063E2B0[], SCR_CODEFUNC_MAX entries
CODEFUNC_COUNT = 35

EVT_KEY_TABLE_VA = 0x63C1D0  # s32 D_0063C1D0[58]: dispatch order
EVT_HANDLER_TABLE_VA = 0x63C420  # handler ptrs D_0063C420[58], indexed by EvtNode kind
EVT_KIND_COUNT = 0x3A

CALC_TABLE_VA = 0x635950  # void* D_00635950[11]: datScriptRunCalc table
CALC_COUNT = 11

BTL_STATE_TABLE_VA = 0x5F7180  # {enter, update, name}, index 0 is NULL, 20 records
BTL_STATE_COUNT = 20
BTL_ACTION_TABLE_VA = 0x5F6E20  # {init, update, name}, 38 records, stride 0xC
BTL_ACTION_COUNT = 38
BTL_CAMERA_TABLE_VA = 0x5F74E4  # 0x14-byte records, retail name at +0, start handler at +4
BTL_CAMERA_COUNT = 50

MARK_RE = re.compile(r"//\s*FUN_([0-9A-Fa-f]{8})")
DEF_RE = re.compile(r"^\s*[A-Za-z_][\w \*]*?\s\**([A-Za-z_]\w*)\s*\(.*$")


class Image:
    def __init__(self, path):
        self.data = pathlib.Path(path).read_bytes()

    def _off(self, va):
        off = va - IMAGE_BASE
        if off < 0 or off + 4 > len(self.data):
            raise ValueError(f"VA 0x{va:08X} outside image.bin")
        return off

    def u32(self, va):
        return struct.unpack_from("<I", self.data, self._off(va))[0]

    def s32(self, va):
        return struct.unpack_from("<i", self.data, self._off(va))[0]

    def cstr(self, va):
        off = self._off(va)
        end = self.data.index(b"\0", off)
        return self.data[off:end].decode("latin-1")


def scan_markers(src_root):
    """Map function VA -> (name, repo-relative file, definition line)."""
    marks = {}
    for path in sorted(src_root.rglob("*.c")):
        lines = path.read_text(encoding="utf-8", errors="replace").split("\n")
        rel = path.relative_to(REPO).as_posix()
        for i, line in enumerate(lines):
            m = MARK_RE.search(line)
            if not m:
                continue
            va = int(m.group(1), 16)
            if va in marks:
                continue
            for j in range(i + 1, min(i + 13, len(lines))):
                d = DEF_RE.match(lines[j])
                if d and not lines[j].strip().endswith(";"):
                    marks[va] = (d.group(1), rel, j + 1)
                    break
    return marks


def resolve(marks, va):
    if va == 0:
        return "NULL", None
    if va in marks:
        name, rel, line = marks[va]
        return name, f"{rel}:{line}"
    return f"func_{va:08x}", None


def load_p4flow(p4_dir):
    names = {}
    for _, _, p4_file in SCRIPT_GROUPS.values():
        for entry in json.loads((p4_dir / p4_file).read_text(encoding="utf-8")):
            names[int(entry["Index"], 16)] = entry["Name"]
    return names


def expect(cond, message):
    if not cond:
        sys.exit(f"dump_dispatch_tables: {message}")


def md_row(cells):
    return "| " + " | ".join(str(c) for c in cells) + " |"


def dump(image, marks, p4names):
    out = []
    out.append("# Retail dispatch tables")
    out.append("")
    out.append(
        "Generated by `tools/dump_dispatch_tables.py` from `image.bin` (VA - 0x100000). "
        "Do not edit by hand; rerun the script."
    )
    out.append("")

    # CodeFunc opcode table (sCodeFuncTable).
    out.append("## Script opcode table (`D_0063E2B0`, sCodeFuncTable)")
    out.append("")
    out.append("Indexed by opcode. Each entry is a `CodeFunc` pointer.")
    out.append("")
    out.append("| Opcode | Handler | Defined at |")
    out.append("|---|---|---|")
    for op in range(CODEFUNC_COUNT):
        fn = image.u32(CODEFUNC_TABLE_VA + 4 * op)
        name, where = resolve(marks, fn)
        out.append(md_row([op, f"`{name}` (0x{fn:08X})", where or "-"]))
    out.append("")

    # Script command groups.
    out.append("## Script command groups (`D_00748530`)")
    out.append("")
    out.append(
        "Group `g` is the 8-byte record `{cmds, count}` at `D_00748530 + g * 8`. "
        "`cmds` is an array of 8-byte `{func, paramCount}` entries. Command id = `g << 12 | index`."
    )
    out.append("")
    for g, (table_va, expected, p4_file) in SCRIPT_GROUPS.items():
        rec = GROUP_TABLE_VA + 8 * g
        cmds = image.u32(rec)
        count = image.u32(rec + 4)
        expect(cmds == table_va, f"group {g} cmds VA 0x{cmds:08X} != 0x{table_va:08X}")
        expect(count == expected, f"group {g} count {count} != {expected}")
        out.append(f"### Group {g} ({p4_file[:-5]}, {count} entries, table 0x{table_va:08X})")
        out.append("")
        out.append("| Command id | Entry | Handler | Defined at | paramCount | p4flow name |")
        out.append("|---|---|---|---|---|---|")
        for idx in range(count):
            fn = image.u32(cmds + 8 * idx)
            pc = image.s32(cmds + 8 * idx + 4)
            cid = (g << 12) | idx
            name, where = resolve(marks, fn)
            p4 = p4names.get(cid, "-")
            out.append(
                md_row([f"0x{cid:04X}", idx, f"`{name}` (0x{fn:08X})", where or "-", pc, p4])
            )
        out.append("")

    # Event node handler table + dispatch order.
    out.append("## Event node tables (`D_0063C1D0`, `D_0063C420`)")
    out.append("")
    out.append(
        "`D_0063C1D0[i]` is the node kind at dispatch-order position `i` (evtKeyIndex inverts it). "
        "`D_0063C420[kind]` is the handler `evtDispatchNode` calls for that kind."
    )
    out.append("")
    out.append("| Kind | Order position | Handler | Defined at |")
    out.append("|---|---|---|---|")
    order = [image.s32(EVT_KEY_TABLE_VA + 4 * i) for i in range(EVT_KIND_COUNT)]
    position = {kind: i for i, kind in enumerate(order)}
    expect(sorted(order) == list(range(EVT_KIND_COUNT)), "D_0063C1D0 is not a permutation of 0..57")
    for kind in range(EVT_KIND_COUNT):
        fn = image.u32(EVT_HANDLER_TABLE_VA + 4 * kind)
        if fn == 0:
            handler, where = "-", "-"
        else:
            name, where_ = resolve(marks, fn)
            handler, where = f"`{name}` (0x{fn:08X})", where_ or "-"
        out.append(md_row([kind, position[kind], handler, where]))
    out.append("")

    # datScriptRunCalc table.
    out.append("## datScriptRunCalc table (`D_00635950`)")
    out.append("")
    out.append("Indexed by calc kind (`DatScriptCalcKind`), `arg0 < 0xB`.")
    out.append("")
    out.append("| Kind | Formula | Defined at |")
    out.append("|---|---|---|")
    for kind in range(CALC_COUNT):
        fn = image.u32(CALC_TABLE_VA + 4 * kind)
        name, where = resolve(marks, fn)
        out.append(md_row([kind, f"`{name}` (0x{fn:08X})", where or "-"]))
    out.append("")

    # Battle state table.
    out.append("## Battle state table (`0x5F7180`, btlMain)")
    out.append("")
    out.append("| # | Name | Enter | Update |")
    out.append("|---|---|---|---|")
    for idx in range(BTL_STATE_COUNT):
        rec = BTL_STATE_TABLE_VA + 12 * idx
        enter, update, name_va = image.u32(rec), image.u32(rec + 4), image.u32(rec + 8)
        if idx == 0:
            expect(enter == 0 and update == 0, "btl state record 0 has function pointers")
            continue
        en, _ = resolve(marks, enter)
        up, _ = resolve(marks, update)
        out.append(md_row([idx, image.cstr(name_va), f"`{en}`", f"`{up}`"]))
    out.append("")

    # Battle action table.
    out.append("## Battle action table (`0x5F6E20`, btlAction)")
    out.append("")
    out.append("| # | Name | Init | Update |")
    out.append("|---|---|---|---|")
    for idx in range(BTL_ACTION_COUNT):
        rec = BTL_ACTION_TABLE_VA + 12 * idx
        init, update, name_va = image.u32(rec), image.u32(rec + 4), image.u32(rec + 8)
        i_name, _ = resolve(marks, init)
        u_name, _ = resolve(marks, update)
        out.append(md_row([idx, image.cstr(name_va), f"`{i_name}`", f"`{u_name}`"]))
    out.append("")

    # Battle camera table.
    out.append("## Battle camera table (`0x5F74E4`, btlCamera)")
    out.append("")
    out.append("Records are 0x14 bytes. Words 2-4 are not named yet and are shown raw.")
    out.append("")
    out.append("| # | Name | Start | Words +8/+0xC/+0x10 |")
    out.append("|---|---|---|---|")
    for idx in range(BTL_CAMERA_COUNT):
        rec = BTL_CAMERA_TABLE_VA + 0x14 * idx
        name_va, start = image.u32(rec), image.u32(rec + 4)
        extra = " ".join(f"0x{image.u32(rec + off):08X}" for off in (8, 12, 16))
        s_name, _ = resolve(marks, start)
        out.append(md_row([idx, image.cstr(name_va), f"`{s_name}`", extra]))
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--image", default=str(REPO / "image.bin"))
    ap.add_argument("--p4flow", default=str(DEFAULT_P4FLOW))
    ap.add_argument("--out", default=str(REPO / "docs" / "dispatch_tables.md"))
    args = ap.parse_args()

    image = Image(args.image)
    marks = scan_markers(REPO / "src")
    p4names = load_p4flow(pathlib.Path(args.p4flow))
    text = dump(image, marks, p4names)
    pathlib.Path(args.out).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
